import { mkdirSync, readFileSync, realpathSync, writeFileSync, lstatSync, renameSync } from "node:fs";
import { randomUUID } from 'node:crypto';
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parse, stringify } from "yaml";
import { validateName } from './softwareteam.mjs';

export const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const expertRoles = ["manage-agent", "need-agent", "home-agent", "code-agent", "review-agent", "test-agent", "run-agent"];
export const expertGroups = Object.fromEntries(expertRoles.map(role => [role, ["manage-agent", "need-agent"].includes(role) ? "product" : "dev"]));

function safeDestination(file, root, directory = false) {
  const parts = path.relative(root, file).split(path.sep);
  let cursor = root;
  for (let i = 0; i < parts.length; i++) {
    cursor = path.join(cursor, parts[i]);
    let stat;
    try { stat = lstatSync(cursor); } catch (error) { if (error.code === 'ENOENT') continue; throw error; }
    const mustBeDirectory = directory || i < parts.length - 1;
    if (stat.isSymbolicLink() || (mustBeDirectory ? !stat.isDirectory() : !stat.isFile())) throw new Error(`Unsafe generated path: ${cursor}`);
  }
}

function writeGenerated(file, bytes) {
  const temporary = `${file}.${randomUUID()}.tmp`;
  writeFileSync(temporary, bytes, { flag: 'wx', mode: 0o600 });
  renameSync(temporary, file);
}

// Keep generated host paths beside the template so startup files keep their authored base.
export function prepareTeam(repoRoot = repositoryRoot, runtime = "codex", name = "software-team") {
  if (!["codex", "claude-code"].includes(runtime)) throw new Error("Runtime must be codex or claude-code");
  const root = realpathSync(repoRoot);
  const teamRoot = path.join(root, "team");
  const spec = parse(readFileSync(path.join(teamRoot, "software-team.template.yaml"), "utf8"));
  spec.name = validateName(name);
  const members = spec.pods.flatMap(pod => pod.members);
  if (members.length !== expertRoles.length || expertRoles.some(role => members.filter(member => member.role === role).length !== 1)) {
    throw new Error("The project team must contain exactly the seven permanent experts");
  }
  if (spec.pods.length !== 2 || spec.pods.some(pod => pod.members.some(member => member.id !== member.role || expertGroups[member.role] !== pod.id))) {
    throw new Error("The permanent experts must use the confirmed product/dev groups and exact IDs");
  }
  const insideRepository = authored => {
    const destination = path.resolve(teamRoot, authored);
    const relative = path.relative(root, destination);
    if (relative === ".." || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
      throw new Error(`Team path leaves the repository: ${authored}`);
    }
    return destination;
  };
  spec.workspace.workspace_root = root;
  spec.workspace.repos = [{ name: "software-team", path: root, kind: "project" }];
  spec.workspace.knowledge_root = insideRepository(spec.workspace.knowledge_root);
  for (const member of members) {
    safeDestination(insideRepository(member.cwd), root, true);
    safeDestination(path.join(teamRoot, "records", member.role), root, true);
    safeDestination(path.join(spec.workspace.knowledge_root, member.role), root, true);
  }
  safeDestination(spec.workspace.knowledge_root, root, true);
  const projectOutput = path.join(teamRoot, 'PROJECT.local.md');
  const output = path.join(teamRoot, "software-team.local.yaml");
  safeDestination(projectOutput, root);
  safeDestination(output, root);
  for (const member of members) {
    if (!member.agent_ref.startsWith("local:")) throw new Error("Expected a repository-local expert definition");
    member.agent_ref = `path:${insideRepository(member.agent_ref.slice("local:".length))}`;
    member.cwd = insideRepository(member.cwd);
    member.runtime = runtime;
  }
  for (const member of members) {
    mkdirSync(member.cwd, { recursive: true });
    mkdirSync(path.join(teamRoot, "records", member.role), { recursive: true });
    mkdirSync(path.join(spec.workspace.knowledge_root, member.role), { recursive: true });
  }
  mkdirSync(spec.workspace.knowledge_root, { recursive: true });
  const startup = readFileSync(path.join(teamRoot, 'PROJECT.md'), 'utf8').replaceAll('@software-team', `@${name}`).replaceAll('--software-team software-team', `--software-team ${name}`);
  writeGenerated(projectOutput, startup);
  spec.startup.files = spec.startup.files.map(file => file.path === 'PROJECT.md' ? { ...file, path: 'PROJECT.local.md' } : file);
  writeGenerated(output, `# Generated by npm run team:prepare; edit software-team.template.yaml instead.\n${stringify(spec)}`);
  return { root, output, spec };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (args.length && (args.length !== 2 || args[0] !== "--runtime")) {
    process.stderr.write("Usage: node scripts/software-team.mjs [--runtime codex|claude-code]\n");
    process.exitCode = 1;
  } else {
    try {
      const { output } = prepareTeam(repositoryRoot, args[1] ?? "codex");
      process.stdout.write(`Prepared ${output}\nNo agents started; candidate SOPs still require human review.\n`);
    } catch (error) {
      process.stderr.write(`${error.message}\n`);
      process.exitCode = 1;
    }
  }
}
